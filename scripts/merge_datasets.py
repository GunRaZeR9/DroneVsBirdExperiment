"""
merge_datasets.py — Phase 1.3 of FIX_PLAN
==========================================
Merge multiple YOLO-format source datasets into one balanced train/val/test
split and write a ready-to-train data.yaml.

Class mapping (target — must be consistent across ALL sources before merging):
  0 = drone
  1 = bird

Usage:
    # Merge existing Data/ with additional downloaded datasets:
    python scripts/merge_datasets.py ^
        --sources D:/Repos/LiceentaBogdan/Data ^
                  D:/Downloads/VisDrone/converted ^
                  D:/Downloads/DroneVsBird ^
        --output  D:/Repos/LiceentaBogdan/datasets/merged ^
        --train-ratio 0.80 ^
        --val-ratio   0.15

    # Dry-run (count only, don't copy files):
    python scripts/merge_datasets.py --dry-run
"""

from __future__ import annotations

import argparse
import os
import random
import shutil
import sys
from pathlib import Path


IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".tiff", ".tif", ".webp"}
SPLITS = ("train", "val", "test")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def collect_images(source_dir: Path) -> list[Path]:
    """Recursively collect all image paths from a source directory."""
    images: list[Path] = []
    for ext in IMAGE_EXTS:
        images.extend(source_dir.rglob(f"*{ext}"))
        images.extend(source_dir.rglob(f"*{ext.upper()}"))
    return images


def label_for_image(img_path: Path) -> Path | None:
    """
    Find the YOLO label .txt for an image using two conventions:
    1. sibling 'labels/' dir:  images/foo.jpg → labels/foo.txt
    2. same directory:         images/foo.jpg → images/foo.txt
    """
    stem = img_path.stem
    # Convention 1: .../images/X.jpg → .../labels/X.txt
    labels_dir = img_path.parent.parent / "labels"
    candidate = labels_dir / (stem + ".txt")
    if candidate.exists():
        return candidate
    # Convention 2: same dir
    candidate2 = img_path.with_suffix(".txt")
    if candidate2.exists():
        return candidate2
    return None


def count_classes_in_label(label_path: Path) -> dict[int, int]:
    """Return {class_id: count} for one label file."""
    counts: dict[int, int] = {}
    try:
        for line in label_path.read_text(encoding="utf-8", errors="ignore").splitlines():
            parts = line.strip().split()
            if parts:
                try:
                    cls = int(parts[0])
                    counts[cls] = counts.get(cls, 0) + 1
                except ValueError:
                    pass
    except OSError:
        pass
    return counts


def copy_pair(img_path: Path, label_path: Path | None, dest_dir: Path, prefix: str = "") -> None:
    """Copy image (and optional label) into dest_dir/{images,labels}/."""
    img_dst = dest_dir / "images"
    lbl_dst = dest_dir / "labels"
    img_dst.mkdir(parents=True, exist_ok=True)
    lbl_dst.mkdir(parents=True, exist_ok=True)

    dst_name = (prefix + img_path.name) if prefix else img_path.name
    shutil.copy2(img_path, img_dst / dst_name)
    if label_path is not None:
        lbl_name = Path(dst_name).stem + ".txt"
        shutil.copy2(label_path, lbl_dst / lbl_name)


def write_data_yaml(output: Path, nc: int, names: list[str]) -> None:
    yaml_text = f"""# Auto-generated by merge_datasets.py
path: {output.as_posix()}
train: train/images
val:   val/images
test:  test/images

nc: {nc}
names:
"""
    for i, name in enumerate(names):
        yaml_text += f"  {i}: {name}\n"
    (output / "data.yaml").write_text(yaml_text, encoding="utf-8")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Merge YOLO datasets and re-split into train/val/test"
    )
    parser.add_argument(
        "--sources",
        nargs="+",
        default=[r"D:\Repos\LiceentaBogdan\Data"],
        help="One or more source dataset root directories",
    )
    parser.add_argument(
        "--output",
        default=r"D:\Repos\LiceentaBogdan\datasets\merged",
        help="Output directory for merged dataset",
    )
    parser.add_argument("--train-ratio", type=float, default=0.80)
    parser.add_argument("--val-ratio",   type=float, default=0.15)
    parser.add_argument("--seed",        type=int,   default=42)
    parser.add_argument(
        "--class-names",
        nargs="+",
        default=["drone", "bird"],
        help="Class names in class-ID order (must match labels in source data)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Count images and show split sizes without copying anything",
    )
    parser.add_argument(
        "--max-images",
        type=int,
        default=0,
        help="Cap total images to this number (0 = no cap)",
    )
    args = parser.parse_args()

    random.seed(args.seed)

    test_ratio = 1.0 - args.train_ratio - args.val_ratio
    if test_ratio < 0:
        print("ERROR: train-ratio + val-ratio must be ≤ 1.0", file=sys.stderr)
        sys.exit(1)

    output = Path(args.output)
    sources = [Path(s) for s in args.sources]

    # -----------------------------------------------------------------------
    # 1. Collect all images across sources
    # -----------------------------------------------------------------------
    print("Scanning sources…")
    all_images: list[Path] = []
    for src in sources:
        if not src.exists():
            print(f"  ⚠  Source not found — skipping: {src}")
            continue
        found = collect_images(src)
        print(f"  {src.name:40s}  {len(found):6,} images")
        all_images.extend(found)

    if not all_images:
        print("ERROR: No images found in any source.", file=sys.stderr)
        sys.exit(1)

    # Remove duplicates by filename stem (last-write wins in order)
    seen: dict[str, Path] = {}
    for img in all_images:
        seen[img.stem] = img
    all_images = list(seen.values())

    random.shuffle(all_images)

    if args.max_images and len(all_images) > args.max_images:
        all_images = all_images[: args.max_images]
        print(f"\nCapped to {args.max_images:,} images (--max-images)")

    n = len(all_images)
    n_train = int(n * args.train_ratio)
    n_val   = int(n * args.val_ratio)
    n_test  = n - n_train - n_val

    split_images = {
        "train": all_images[:n_train],
        "val":   all_images[n_train : n_train + n_val],
        "test":  all_images[n_train + n_val :],
    }

    # -----------------------------------------------------------------------
    # 2. Report
    # -----------------------------------------------------------------------
    print(f"\nTotal unique images : {n:,}")
    print(f"  train : {n_train:6,}  ({args.train_ratio*100:.0f}%)")
    print(f"  val   : {n_val:6,}  ({args.val_ratio*100:.0f}%)")
    print(f"  test  : {n_test:6,}  ({test_ratio*100:.0f}%)")

    # Class distribution preview (from labels)
    print("\nClass distribution (sampled from train labels)…")
    sample_imgs = split_images["train"][:500]
    cls_counts: dict[int, int] = {}
    no_label = 0
    for img in sample_imgs:
        lbl = label_for_image(img)
        if lbl is None:
            no_label += 1
            continue
        for cls, cnt in count_classes_in_label(lbl).items():
            cls_counts[cls] = cls_counts.get(cls, 0) + cnt

    for cls_id, name in enumerate(args.class_names):
        n_ann = cls_counts.get(cls_id, 0)
        print(f"  {name:10s} (class {cls_id}): {n_ann:,} annotations in sample")
    if no_label:
        print(f"  (images with no label file: {no_label})")

    if args.dry_run:
        print("\nDry-run complete — no files copied.")
        return

    # -----------------------------------------------------------------------
    # 3. Copy files
    # -----------------------------------------------------------------------
    print(f"\nCopying to {output} …")
    stats = {"train": 0, "val": 0, "test": 0}

    for split, imgs in split_images.items():
        dest = output / split
        for img in imgs:
            lbl = label_for_image(img)
            copy_pair(img, lbl, dest)
            stats[split] += 1
        print(f"  {split:6s}: {stats[split]:,} images copied")

    # -----------------------------------------------------------------------
    # 4. Write data.yaml
    # -----------------------------------------------------------------------
    write_data_yaml(output, nc=len(args.class_names), names=args.class_names)
    print(f"\ndata.yaml written to {output / 'data.yaml'}")

    print("\n✓ Merge complete.")
    print("  Next step: python scripts/train_yolov10.py")


if __name__ == "__main__":
    main()
